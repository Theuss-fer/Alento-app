export function livrosDaTradicao(tradicao) {
  if (tradicao === 'evangelica') {
    return LIVROS.filter((livro) => !livro.deutero);
  } else if (tradicao === 'catolica') {
    return LIVROS;
  } else {
    throw new Error(`Tradição desconhecida: ${tradicao}`);
  }
}